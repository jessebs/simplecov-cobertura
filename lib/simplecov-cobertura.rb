# frozen_string_literal: true

require 'rexml/text'
require 'pathname'
require 'simplecov'

require_relative 'simplecov-cobertura/version'

module SimpleCov
  module Formatter
    class CoberturaFormatter
      RESULT_FILE_NAME = 'coverage.xml'
      DTD_URL = 'http://cobertura.sourceforge.net/xml/coverage-04.dtd'

      EMPTY_HASH = {}.freeze
      private_constant :EMPTY_HASH

      # Extracts the start line out of a stringified branch condition key, e.g.
      # '[:if, 0, 3, 4, 3, 21]' -> 3. The lazy \D+? keeps a negative second
      # number from being read as a positive one.
      CONDITION_START_LINE_PATTERN = /-?\d+\D+?(-?\d+)/
      private_constant :CONDITION_START_LINE_PATTERN

      def initialize(result_file_name: RESULT_FILE_NAME)
        @result_file_name = result_file_name
      end

      def format(result)
        xml_str = result_to_xml result
        result_path = File.join(SimpleCov.coverage_path, @result_file_name)

        File.write(result_path, xml_str)
        puts output_message(result, result_path)

        xml_str
      end

      private

      def result_to_xml(result)
        branch_coverage = SimpleCov.branch_coverage?

        xml = +"<?xml version='1.0'?>\n"
        xml << '<!DOCTYPE coverage SYSTEM "' << DTD_URL << "\">\n"
        xml << '<!--Generated by simplecov-cobertura version ' << VERSION <<
               " (https://github.com/jessebs/simplecov-cobertura)-->\n"

        xml << '<coverage'
        append_coverage_attributes(xml, result, branch_coverage)
        xml << ">\n"

        xml << "  <sources>\n    <source>" << escape(SimpleCov.root) << "</source>\n  </sources>\n"

        groups = result.groups
        groups = { File.basename(SimpleCov.root) => result.files } if groups.empty?
        append_packages(xml, groups, branch_coverage)

        xml << '</coverage>'
      end

      def append_packages(xml, groups, branch_coverage)
        packages = groups.reject { |_name, files| files.empty? }
        return xml << "  <packages/>\n" if packages.empty?

        xml << "  <packages>\n"
        packages.each do |name, files|
          xml << '    <package'
          append_package_attributes(xml, name, files, branch_coverage)
          xml << ">\n      <classes>\n"

          files.each { |file| append_class(xml, file, branch_coverage) }

          xml << "      </classes>\n    </package>\n"
        end
        xml << "  </packages>\n"
      end

      def append_class(xml, file, branch_coverage)
        xml << '        <class'
        append_class_attributes(xml, file, branch_coverage)
        xml << ">\n          <methods/>\n"

        branches_by_line = branch_coverage ? build_branches_by_line(file) : EMPTY_HASH
        lines = file.lines.select { |file_line| file_line.covered? || file_line.missed? }

        if lines.empty?
          xml << "          <lines/>\n"
        else
          xml << "          <lines>\n"
          lines.each { |file_line| append_line(xml, file_line, branches_by_line, branch_coverage) }
          xml << "          </lines>\n"
        end

        xml << "        </class>\n"
      end

      def append_line(xml, file_line, branches_by_line, branch_coverage)
        xml << '            <line number="' << file_line.line_number.to_s <<
               '" hits="' << file_line.coverage.to_s << '"'
        append_branch_attributes(xml, file_line, branches_by_line) if branch_coverage
        xml << "/>\n"
      end

      def append_coverage_attributes(xml, result, branch_coverage)
        ls = result.coverage_statistics[:line]

        xml << ' line-rate="' << extract_rate(ls.percent) <<
               '" lines-covered="' << ls.covered.to_s <<
               '" lines-valid="' << ls.total.to_s << '"'
        if branch_coverage
          bs = result.coverage_statistics[:branch]
          xml << ' branches-covered="' << bs.covered.to_s <<
                 '" branches-valid="' << bs.total.to_s <<
                 '" branch-rate="' << extract_rate(bs.percent) << '"'
        end
        xml << ' complexity="0" version="0" timestamp="' << Time.now.to_i.to_s << '"'
      end

      def append_package_attributes(xml, name, result, branch_coverage)
        ls = result.coverage_statistics[:line]

        xml << ' name="' << escape(name) << '" line-rate="' << extract_rate(ls.percent) << '"'
        if branch_coverage
          bs = result.coverage_statistics[:branch]
          xml << ' branch-rate="' << extract_rate(bs.percent) << '"'
        end
        xml << ' complexity="0"'
      end

      def append_class_attributes(xml, file, branch_coverage)
        ls = file.coverage_statistics[:line]
        filename = escape(resolve_filename(file.filename))

        xml << ' name="' << filename << '" filename="' << filename <<
               '" line-rate="' << extract_rate(ls.percent) << '"'
        if branch_coverage
          bs = file.coverage_statistics[:branch]
          xml << ' branch-rate="' << extract_rate(bs.percent) << '"'
        end
        xml << ' complexity="0"'
      end

      def append_branch_attributes(xml, file_line, branches_by_line)
        branch_info = branches_by_line[file_line.line_number]
        if branch_info
          total, covered = branch_info
          pct_coverage = total > 0 ? (covered * 100 / total) : 0
          xml << ' branch="true" condition-coverage="' << pct_coverage.to_s <<
                 '% (' << covered.to_s << '/' << total.to_s << ')"'
        else
          xml << ' branch="false"'
        end
      end

      # Maps a line number to a [total, covered] pair of branch counts.
      def build_branches_by_line(file)
        branches_by_line = {}
        file.coverage_data.fetch('branches', EMPTY_HASH).each do |condition, branches|
          line = condition_start_line(condition)
          next unless line

          counts = branches_by_line[line] ||= [0, 0]
          branches.each_value do |hit_count|
            counts[0] += 1
            counts[1] += 1 if hit_count.to_i > 0
          end
        end
        branches_by_line
      rescue StandardError => e
        warn "simplecov-cobertura: couldn't extract per-line branch detail " \
               "(#{e.class}: #{e.message}); lines will report branch=\"false\""
        EMPTY_HASH
      end

      def condition_start_line(condition)
        return condition[2] if condition.is_a?(Array)
        return nil unless condition.is_a?(String)

        match = CONDITION_START_LINE_PATTERN.match(condition) # [id, start_line, ...]
        match && match[1].to_i
      end

      # Roughly mirrors private method SimpleCov::Formatter::HTMLFormatter#output_coverage
      def output_message(result, output_path)
        output = "Coverage report generated for #{result.command_name} to #{output_path}."
        output += "\nLine Coverage: #{result.covered_percent.round(2)}% (#{result.covered_lines} / #{result.total_lines})"
        output += "\nBranch Coverage: #{result.coverage_statistics[:branch].percent.round(2)}% (#{result.covered_branches} / #{result.total_branches})" if SimpleCov.branch_coverage?
        output
      end

      # Files normally live under the project root, so the relative path is a
      # plain suffix of the absolute one. Anything else (a file outside the
      # root, a path needing cleanup) falls back to Pathname, which is
      # accurate but allocates heavily for something done once per file.
      def resolve_filename(filename)
        prefix = root_prefix
        if filename.start_with?(prefix)
          relative = filename[prefix.length..]
          unless relative.empty? || relative.start_with?('.') ||
                 relative.include?('/.') || relative.include?('//')
            return relative
          end
        end

        Pathname.new(filename).relative_path_from(project_root).to_s
      end

      def extract_rate(percent)
        (percent / 100).round(4).to_s
      end

      def project_root
        @project_root ||= Pathname.new(SimpleCov.root)
      end

      def root_prefix
        @root_prefix ||= File.join(SimpleCov.root, '')
      end

      def escape(text)
        REXML::Text.normalize(text.to_s)
      end
    end
  end
end
